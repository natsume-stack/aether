import fs from 'node:fs';
import path from 'node:path';

/** Bundle compiler-emitted declarations for VS Code, without bundling runtime code or copying standard libraries. */
export function bundleServerTypes() {
  const root = path.resolve(__dirname, '../../..');
  const source = path.join(root, 'apps/game/scripts/assets/api');
  const target = path.join(root, 'packages/script-api/dts/box3-server-api.d.ts');
  function collect(directory: string): string[] {
    return fs.readdirSync(directory, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name)).flatMap(entry => {
      const file = path.join(directory, entry.name);
      return entry.isDirectory() ? collect(file) : entry.name.endsWith('.d.ts') ? [fs.readFileSync(file, 'utf8')] : [];
    });
  }
  const content = [
    '// Generated by apps/game/scripts/build-apis.ts. Do not edit.',
    '/// <reference lib="es2020" />',
    fs.readFileSync(path.join(source, 'globals.d.ts'), 'utf8'),
    ...collect(path.join(source, 'js')),
  ].join('\n').trimEnd() + '\n';
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== content) fs.writeFileSync(target, content);
  console.log(`Standalone server declarations: ${target}`);
}
