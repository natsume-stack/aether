const ranks = new Map(PACKAGE_FIELD_ORDER.map((key, index) => [key, index]));

/** Preserve values and nested ordering; unknown extension keys retain their relative order. */
function orderPackageManifest(manifest) {
    return Object.fromEntries(
        Object.entries(manifest).sort(
            ([left], [right]) => (ranks.get(left) ?? ranks.size) - (ranks.get(right) ?? ranks.size),
        ),
    );
}

module.exports = { orderPackageManifest };
